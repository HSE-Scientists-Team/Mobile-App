package org.matchlab.academic_net.di

import me.tatarka.inject.annotations.Component
import me.tatarka.inject.annotations.KmpComponentCreate
import me.tatarka.inject.annotations.Provides
import org.matchlab.academic_net.Backend
import org.matchlab.academic_net.analytics.Analytics
import org.matchlab.academic_net.analytics.NoOpAnalytics
import org.matchlab.academic_net.analytics.StatisticsPreference
import org.matchlab.academic_net.feature.auth.domain.AuthRepository
import org.matchlab.academic_net.feature.auth.ui.AuthUiDependencies
import org.matchlab.academic_net.securestore.SecureStore

/**
 * The object graph of the process, generated by kotlin-inject: what exists whether or not somebody is signed in. That
 * is the sign-in (its data source, repository and use cases), the Gateway client it talks through and the analytics
 * (the platform's SDK and the choice of the person to use it); everything else belongs to one signed-in user and lives
 * in the [SessionComponent] of that session, a child of this graph.
 *
 * The sign-in data source is the Gateway's (see [AuthModule]); the source of every other feature is picked in
 * [DataSourcesModule].
 */
@AppScope
@Component
internal abstract class AppComponent(
    /** The platform's encrypted storage (Android Keystore, iOS Keychain); the app gets it from its entry point. */
    @get:Provides val secureStore: SecureStore,
    /** The address of the Gateway; fixed for the process. */
    @get:Provides val backend: Backend,
    /** How the Gateway client is made; the platform's engine, except in tests. */
    @get:Provides val gateways: GatewayFactory,
    /** The platform's analytics SDK behind the shared contract; [NoOpAnalytics] when the platform gives none. */
    @get:Provides val analytics: Analytics,
) : GatewayModule,
    AuthModule,
    AnalyticsModule {
    /** What the sign-in screens and the root of the app need. */
    abstract val auth: AuthUiDependencies

    /** The one repository of the session state: the session graphs report a refused token to it. */
    abstract val authRepository: AuthRepository

    /** The choice "send usage statistics" of this device: the value that the analytics, settings and sign-up share. */
    abstract val preference: StatisticsPreference
}

/**
 * Creates the process graph; the implementation is generated for each target. [gateways] is the platform's by
 * default; a test passes its own to run the graph over a mock engine. [analytics] is the platform's SDK, and without
 * one the graph gets [NoOpAnalytics].
 */
@KmpComponentCreate
internal expect fun createAppComponent(
    secureStore: SecureStore,
    backend: Backend,
    gateways: GatewayFactory = GatewayFactory.Default,
    analytics: Analytics = NoOpAnalytics,
): AppComponent
